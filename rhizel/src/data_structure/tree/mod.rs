//! 堆
//!
//! 1. 什么是堆？
//! 堆是一种满足以下条件的树：
//!     堆中的每一个节点值都大于等于（或小于等于）子树中所有节点的值。
//!     或者说，任意一个节点的值都大于等于（或小于等于）所有子节点的值。
//!
//! 2. 堆的用途？
//! 当我们只关心所有数据中的最大值或者最小值，存在多次获取最大值或者最小值，多次插入或删除数据时，就可以使用堆。
//! 相对有序数组而言，堆的主要优势在于插入和删除数据效率较高。
//!
//! 3. 堆的分类？
//! 堆分为最大堆和最小堆。
//! 最大堆：堆中的每一个节点的值都大于等于子树中所有节点的值。
//! 最小堆：堆中的每一个节点的值都小于等于子树中所有节点的值。
//!

